// "Measure now" session for iOS (DESIGN.md 3.3, docs/platforms.md).
//
// What this skeleton does: a user-started 30-60 minute session with the app in the foreground and the
// idle timer disabled, CMMotionManager accelerometer updates requested at 100 Hz, sample timestamps
// mapped to UTC, a measured sample rate, and a stop on time-out or when the user ends it.
//
// What it does NOT do yet (TODO, see the list at the bottom): the spectral pipeline. Samples are
// counted and discarded; nothing is stored or uploaded. The pipeline must be a port of
// android/dsp-core (same rules, same constants) validated against tests/vectors/stream_b, which is the
// 100 Hz-grid case an iPhone at about 100 Hz will take.

import CoreMotion
import Foundation
import UIKit

final class MeasureSession: ObservableObject {
    enum State: Equatable { case idle, running, finished(String) }

    @Published private(set) var state: State = .idle
    @Published private(set) var samples = 0
    @Published private(set) var measuredRate: Double = 0
    @Published private(set) var elapsed: TimeInterval = 0

    private let motion = CMMotionManager()
    private let queue: OperationQueue = {
        let q = OperationQueue()
        q.name = "quakescore.motion"
        q.maxConcurrentOperationCount = 1
        return q
    }()
    private var timer: Timer?
    private var startDate = Date()
    private var duration: TimeInterval = 45 * 60
    private var firstT: Double = .nan
    private var lastT: Double = .nan
    private var count = 0          // touched only on the motion queue
    /// UTC seconds minus CMLogItem timestamp seconds (time since boot). Source "none" until SNTP exists.
    private var utcOffset: Double = 0

    static let gravity = 9.80665   // CoreMotion reports acceleration in units of g

    func start(minutes: Int) {
        guard state != .running, motion.isAccelerometerAvailable else { return }
        duration = TimeInterval(min(max(minutes, 30), 60) * 60)
        samples = 0
        count = 0
        firstT = .nan
        lastT = .nan
        startDate = Date()
        // TODO: replace by an SNTP sample (offset and delay) at start, every 10 min and at the end,
        // fitted linearly as in android/dsp-core TimeBase. Until then sync_source would be "none".
        utcOffset = Date().timeIntervalSince1970 - ProcessInfo.processInfo.systemUptime
        UIApplication.shared.isIdleTimerDisabled = true
        motion.accelerometerUpdateInterval = 1.0 / 100.0
        motion.startAccelerometerUpdates(to: queue) { [weak self] data, _ in
            guard let self, let d = data else { return }
            let t = d.timestamp + self.utcOffset                 // UTC seconds
            let x = d.acceleration.x * Self.gravity
            let y = d.acceleration.y * Self.gravity
            let z = d.acceleration.z * Self.gravity
            self.consume(t: t, x: x, y: y, z: z)
        }
        state = .running
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            guard let self else { return }
            self.elapsed = Date().timeIntervalSince(self.startDate)
            if self.elapsed >= self.duration { self.stop(reason: "time limit") }
        }
    }

    func stop(reason: String = "stopped by user") {
        guard state == .running else { return }
        motion.stopAccelerometerUpdates()
        timer?.invalidate()
        timer = nil
        UIApplication.shared.isIdleTimerDisabled = false
        // TODO: finish the processor, build the schema v1 JSON with "platform": "ios", queue the upload.
        state = .finished(reason)
    }

    private func consume(t: Double, x: Double, y: Double, z: Double) {
        if firstT.isNaN { firstT = t }
        if !lastT.isNaN && !(t > lastT) { return }   // same rule as dsp-core: time must increase
        lastT = t
        // TODO: processor.push(t, x, y, z) -- port of android/dsp-core SessionProcessor.
        _ = (x, y, z)
        count += 1
        let n = count
        let t0 = firstT
        DispatchQueue.main.async {
            self.samples = n
            if n > 1, t > t0 { self.measuredRate = Double(n - 1) / (t - t0) }
        }
    }
}

